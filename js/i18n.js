    var lang = null;

    function detect() {
        var nav = (typeof navigator !== 'undefined') ? navigator : {};
        var bl = (nav.language || nav.userLanguage || '').toLowerCase();
        if (bl.indexOf('km') === 0) return 'km';
        if (bl.indexOf('zh') === 0) return 'zh';
        return 'en';
    }

    function init() {
        var saved = null;
        try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
        lang = saved || detect();
        if (LANGS.indexOf(lang) === -1) lang = DEFAULT_LANG;
        if (document.documentElement) document.documentElement.lang = lang;
    }

    function set(l) {
        if (LANGS.indexOf(l) === -1) return;
        lang = l;
        try { localStorage.setItem(STORAGE_KEY, l); } catch (e) {}
        if (document.documentElement) document.documentElement.lang = l;
        apply();
        renderSwitcher();
        // 通知页面其它动态渲染逻辑（如 marquee、产品卡片）重新渲染以反映新语言
        try {
            window.dispatchEvent(new CustomEvent('i18n:langchange', { detail: { lang: l } }));
        } catch (e) {}
    }

    function t(key, fallback) {
        var l = lang || DEFAULT_LANG;
        var d = dict[l];
        if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
        d = dict.zh;
        if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
        return fallback != null ? fallback : key;
    }

    function apply() {
        // data-i18n → textContent
        var nodes = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].textContent = v;
        }
        // data-i18n-html → innerHTML
        nodes = document.querySelectorAll('[data-i18n-html]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n-html');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].innerHTML = v;
        }
        // data-i18n-ph → placeholder
        nodes = document.querySelectorAll('[data-i18n-ph]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n-ph');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].placeholder = v;
        }
        // data-i18n-title → title attribute
        nodes = document.querySelectorAll('[data-i18n-title]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n-title');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].setAttribute('title', v);
        }
        // data-i18n-aria → aria-label attribute (本地化无障碍标签)
        nodes = document.querySelectorAll('[data-i18n-aria]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n-aria');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].setAttribute('aria-label', v);
        }
        // data-i18n-alt → alt attribute (本地化图片/区域替代文本)
        nodes = document.querySelectorAll('[data-i18n-alt]');
        for (var i = 0; i < nodes.length; i++) {
            var k = nodes[i].getAttribute('data-i18n-alt');
            var v = t(k, null);
            if (v !== null && v !== k) nodes[i].setAttribute('alt', v);
        }
        // 同步 document.title
        syncTitle();
    }

    function syncTitle() {
        // 尝试取当前页面的 title key (每个页面的 <title data-i18n="title.xxx"> 或推断)
        var titleEl = document.querySelector('title[data-i18n]');
        if (titleEl) {
            var k = titleEl.getAttribute('data-i18n');
            var v = t(k, null);
            if (v && v !== k) document.title = v;
            return;
        }
        // fallback: 按 body data-page-type 推断
        var body = document.body;
        if (!body) return;
        var pageType = body.getAttribute('data-page') || '';
        var titleKey = null;
        if (pageType === 'index' || pageType === 'home') titleKey = 'title.index';
        else if (pageType === 'products') titleKey = 'title.products';
        else if (pageType === 'articles') titleKey = 'title.articles';
        if (titleKey) {
            var v = t(titleKey, null);
            if (v && v !== titleKey) document.title = v;
        }
    }

